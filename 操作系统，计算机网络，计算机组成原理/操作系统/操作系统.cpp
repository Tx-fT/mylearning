//18.
//处理机调度的概念层次：
//有一些任务要处理时，由于资源有限，没办法同时处理。需要确定某种规则来确定这些任务的顺序
//高级调度（作业调度）：好几个程序要启动，到底先启动哪个，从作业队列挑选一个调入内存（创建PCB），调出撤销PCB，每个作业只能一次
//低级调度（进程调度/处理机调度）：
//从就绪队列中选一个进程，处理机分配给他，最基本频率很高
//中级调度（内存调度）：
//内存不够某些程序调出外存，然后在重新调入内存
//等待状态--挂起状态，成挂起队列
//按照某种策略决定哪个处于挂起状态的进程重新调入内存，一个进程会多次调入调出内存，频率比高级调度高
//就绪挂起：在就绪态因内存挂起，激活，还可由创建态，运行态，阻塞挂起态达到
//阻塞挂起：在阻塞态因内存挂起，激活/或(某事件出现)->就绪挂起
//阻塞态的进程映像在内存，挂起在外存
