//16.
//线程的实现方式和多线程模型
//用户级线程：
//早期操作系统只支持进程不支持线程，线程有线程库实现，实现线程的创建调度和销毁
//线程切换在用户态不需要变态，开销小，效率高
//操作系统意识不到线程，当一个用户级线程被阻塞，整个进程都会被阻塞，不能在处理机并行运行
//内核级线程：
//由操作系统支持的线程，需要cpu的变态在核心态下完成，并发能力强，但开销大
//多线程模型：
//一对一（一个用户级线程对应一个内核级线程）
//多对一……内核级线程才是处理机分配的单位
//多对多，克服一对一占用太多内核级线程开销大，克服多对一模型并发度不高的缺点
//一段用户线程（“代码逻辑”）只有获得了内核级线程（“运行机会”）才能被cpu执行，内核级线程可以运行任意一个有映射关系的用户级线程

