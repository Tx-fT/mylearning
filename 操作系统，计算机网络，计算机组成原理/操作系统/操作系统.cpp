//12.
//进程控制：
//进程的状态的转换
//由原语实现，原语具有原子性，执行不可被中断，“关中断”“开中断”两个特权指令实现原子性（内核程序）
//cpu执行关中断指令后，不再检查中断信号，直到执行开中断才会恢复检查
//一/进程的创建：
//1创建原语：申请空白PCB，为新进程分配所需资源，初始化PCB，将PCB插入就绪队列（创建态->就绪态）
//2引起进程创建的事件：用户登录，作业调度，提供服务，应用请求
//二/进程的终止：
//1撤销原语：从PCB集合找到终止进程的PCB，若进程正在运行，立即剥夺cpu，将cpu分配给其他进程，终止其所有子进程,将该进程拥有的所有资源归还父进程或操作系统，删除PCB
//2引起进程终止的事件：正常结束（exit），异常结束（/0），外界干预
//三/进程的阻塞和唤醒：
//进程的阻塞：
//1.阻塞原语：找到pcb，保护现场，state成阻塞态，下处理机插入等待队列
//进程的唤醒：
//1.唤醒原语：在等待队列找到pcb，等待队列移除，设置就绪态插入就绪队列
//2.事件：因什么阻塞
//四/进程的切换（运行态->就绪态，就绪态->运行态）：
//1.切换原语：运行环境（程序中间结果）存入pcb，pcb移入相应队列，选择另一个进程执行更新pcb，恢复新进程运行环境
//cpu寄存器：psw，pc，ir，当要中间切换进程pcb中保存下
//总结：更新pcb中的信息（运行环境，state），将pcb插入合适的队列，分配/回收资源

//13.
//进程通信（IPC）
//两个或多个进程差生了数据交互
//共享存储：
//申请共享存储区，各个进程访问互斥（操作系统内核提供同步互斥工具PV操作）
//基于数据结构的共享--低级通信
//基于存储区的共享--高级通信
//消息传递：
//以格式化的消息为单位，进程通过操作系统提供的“发送消息/接收消息”两个原语进行数据交换
//消息头+消息体
//直接通信方式（消息发送进程要指明接收进程的id）：
//发送原语：send（接收方，msg）->进程Q消息队列->接受原语：receive（发送方，&msg）
//间接通信方式（通过“信箱”间接的通信。因此又称“信箱通信方式”
//进程p像操作系统申请“信箱”->send（信箱，msg）->进程Q：receive（信箱，&msg）
//可以多个进程对一个信箱
//管道通信：
//“管道”是一个特殊的共享文件，又名pipe文件。其实就是在内存中开辟一个大小固定的内存缓冲区
//与共享存储不同的是有优先级先进先出（循环队列，数据流的形式）而不是无限制
//管道只能采用“半双工通信”（同一时刻只能实现单向传输）。如果要实现全双工通信，则要设置两个管道
//各个进程互斥访问管道
//管道中的数据一旦被读出，就彻底消失，多个进程同时读一个管道可能会错乱：1.一个管道允许多个写进程一个读进程2.让读进程轮流从管道中读数据

