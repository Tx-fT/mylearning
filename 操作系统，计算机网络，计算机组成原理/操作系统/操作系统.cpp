//操作系统的体系结构：
//内核：内核是操作系统最核心最基本的部分，实现操作系统内核功能的那些程序就是内核程序。
//    1.（硬件关联紧密）时钟管理，中断处理，原语：特殊的程序，处于操作系统的最底层，最接近硬件，具有原子性（运行不可中断），运行时间较短操作频繁
//    2.（更多对数据结构的操作）对系统资源进行管理的功能：进程管理，存储器管理，设备管理
//1何2叫大内核，1叫微内核->运行在内核态，其它非内核功能运行在用户态，微内核2也在用户态
//分层结构：便于调试验证，接口清晰。仅可以调用相邻低层，难以合理定义各层边界，效率低不能跨层调用
//模块化：将内核划分为多个模块，之间相互协作
//       内核=主模块+可加载的内核模块，主模块：只负责核心功能，如进程调度，内存管理。可加载的内核模块：动态加载新模块无需编译整个内核
